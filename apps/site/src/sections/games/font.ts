const rows = (ch: string) => (Glyph[ch] ?? Glyph[' ']).split('/')

// 글자 사이 1 칸을 띄운 전체 폭 (그림자 제외)
export const textWidth = (txt: string) => [...txt].reduce((a, ch) => a + rows(ch)[0].length + 1, -1)

// 캔버스 가운데에 그림자 먼저, 그 위에 흰 글씨
export const drawText = (ctx: CanvasRenderingContext2D, txt: string, shadow = '#3b3050', fill = '#ffffff') => {
  const { width } = ctx.canvas
  ctx.clearRect(0, 0, width, ctx.canvas.height)
  let X = Math.round((width - textWidth(txt)) / 2)
  for (const ch of txt) {
    const G = rows(ch)
    for (const [C, Dx] of [
      [shadow, 1],
      [fill, 0],
    ] as const) {
      ctx.fillStyle = C
      G.forEach((row, y) => [...row].forEach((c, x) => c === '#' && ctx.fillRect(X + x + Dx, y + Dx, 1, 1)))
    }
    X += G[0].length + 1
  }
}
